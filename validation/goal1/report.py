"""Write docs/validation.md from validation/results/goal1_*.json."""
from __future__ import annotations

import json
from pathlib import Path

TARGETS = {"recall": (">=", 0.85), "exact_turn": (">=", 0.80), "false_positive": ("<=", 0.05)}
TYPES = ("STALE_FACT", "RECALL_MISS", "CONSTRAINT_DROP", "USER_REPAIR")


def _cell(m: dict, metric: str, check: bool) -> str:
    r = m[metric]
    if r["n"] == 0:
        return "n/a"
    text = f"{r['rate']:.2f} ({r['k']}/{r['n']}, CI {r['ci95'][0]:.2f}-{r['ci95'][1]:.2f})"
    if not check:
        return text
    op, bar = TARGETS[metric]
    ok = r["rate"] >= bar if op == ">=" else r["rate"] <= bar
    return text + (" ✅" if ok else " ❌")


def _table(agg: dict, split: str, check: bool) -> list[str]:
    lines = ["| Type | Recall | Exact turn | False positives |", "|---|---|---|---|"]
    for typ in TYPES + ("ALL",):
        m = agg.get(f"{split}|{typ}|all")
        if m:
            lines.append(f"| {typ} | {_cell(m, 'recall', check)} | {_cell(m, 'exact_turn', check)} | "
                         f"{_cell(m, 'false_positive', check)} |")
    return lines


def _attr_table(agg: dict, split: str) -> list[str]:
    lines = ["| Type | Group | Recall | Exact turn | False positives |", "|---|---|---|---|---|"]
    for key, m in agg.items():
        s, typ, attr = key.split("|")
        if s == split and attr != "all" and typ != "ALL":
            lines.append(f"| {typ} | {attr} | {_cell(m, 'recall', False)} | {_cell(m, 'exact_turn', False)} | "
                         f"{_cell(m, 'false_positive', False)} |")
    return lines


def write_report(results_dir: Path, out: Path) -> None:
    runs = [json.loads(p.read_text()) for p in sorted(results_dir.glob("goal1_*.json"))]
    lines = ["# Validation", "",
             "Generated by `python -m validation.goal1`; do not edit by hand. Targets were pre-registered in",
             "`docs/ROADMAP.md` before the harness existed. ✅/❌ mark held-out results against them.", "",
             "## Goal 1: does memdiag find injected memory failures at the right turn?", "",
             "Each case is one or more clean LongMemEval-S sessions with exactly one injected failure at a known turn, "
             "plus a paired control (same sessions, a look-alike that is not a failure). **Recall**: the case has a "
             "finding of the right type. **Exact turn**: that finding is on the injected turn. **False positives**: "
             "controls with a finding of their type. 95% Wilson intervals. Method: `docs/plans/M6.md`.", ""]
    for r in runs:
        meta = r["meta"]
        mode = meta["mode"] + (f" ({meta['judge_model']})" if meta.get("judge_model") else "")
        lines += [f"### Mode: {mode}", "",
                  f"Run {meta['date']} · memdiag {meta['memdiag_version']} · commit {meta['commit']} · data sha256 "
                  f"`{meta['data_sha256'][:12]}…` · {meta['cases']} cases"
                  + (f" (limited to {meta['limit']} per type and split)" if meta.get("limit") else "")
                  + (f" ({meta['split']} split only)" if meta.get("split") else ""), "",
                  f"Background: {meta['background']['rejected']} of {meta['background']['checked']} base sessions had a "
                  "finding before any injection and were excluded (not counted as false positives).", "",
                  "**Held-out** (held-out templates and sessions; the headline numbers):", ""]
        lines += _table(r["aggregate"], "heldout", True) + [""]
        if r.get("flip"):
            f = r["flip"]
            lines += [f"Flip rate over {f['reruns']} uncached reruns: {f['flipped']}/{f['cases']} cases "
                      f"({f['rate']:.2%}) {'✅' if f['rate'] <= 0.05 else '❌'} (target <= 5%).", ""]
        if any(k.startswith("dev|") for k in r["aggregate"]):
            lines += ["**Dev** (what detectors may be tuned on):", ""] + _table(r["aggregate"], "dev", False) + [""]
        lines += ["By attribute or instruction kind (held-out):", ""] + _attr_table(r["aggregate"], "heldout") + [""]
    lines += ["## Threats to validity", "",
              "- Injected failures are short and explicit; real failures are subtler. Treat recall here as an upper "
              "bound for real logs. External validity (real labels, human agreement) is Goal 2.",
              "- Base conversations are LLM-generated (LongMemEval). Some phrasings overlap with detector rules; "
              "held-out templates include phrasings the rules were not written for.",
              "- In LLM mode one local model is extractor and judge; a second judge family has not been run yet.",
              "- Controls test specific look-alikes, not every way a detector can misfire on real logs.", ""]
    out.write_text("\n".join(lines))
